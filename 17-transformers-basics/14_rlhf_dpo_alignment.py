"""
第十四课：让模型学会“听话” —— RLHF 与 DPO 对齐技术
=============================================================
业务背景：
  你在网上下载的开源模型，经常分为两个版本：
  - Base 模型（如 Qwen2.5-7B）：它只是个“无情的文字接龙机”。你问它“如何做红烧肉？”，
    它可能不回答，而是续写一句“如何做清蒸鱼？”（因为它在模仿网上的提问列表）。
  - Instruct / Chat 模型（如 Qwen2.5-7B-Instruct）：它是能正常和你对话的“智能助手”。

  从 Base 模型变成 Instruct 模型的过程，叫做“对齐（Alignment）”。

核心技术：
  1. SFT (监督微调)：教模型“回答问题该有的格式”。
  2. RLHF (人类反馈强化学习)：给模型打分，教它“什么回答是好的，什么是有害的”。
  3. DPO (直接偏好优化)：RLHF 太难搞了（需要弄 4 个模型互相打架），DPO 通过巧妙的数学转化，
     直接用“正确答案”和“错误答案”对撞，极大降低了微调的门槛，是目前的绝对主流。

本课目标：
  理解大模型是如何被“调教”出价值观和逻辑判断的。
"""

def demo_alignment_concepts():
    print("=" * 60)
    print("⚖️ 演示：大模型的价值观对齐 (Alignment)")
    print("=" * 60)
    
    print("【第一阶段：Pre-Training (预训练 Base 模型)】")
    print("  状态：读完了全人类互联网的数据，脑容量极大，但不知道怎么和人类交流。")
    print("  用户输入: '讲个笑话'")
    print("  模型输出: '，并分析其中的幽默元素。' (把它当成了阅读理解题去续写)\n")
    
    print("【第二阶段：SFT (监督微调)】")
    print("  做法：人类写了几万条标准的 <提问> 和 <高质量回答>。")
    print("  状态：模型学会了人类对话的'格式'。")
    print("  用户输入: '讲个笑话'")
    print("  模型输出: '好的。有一天，一只番茄过马路...'\n")
    
    print("【第三阶段：DPO (直接偏好优化，替代了繁琐的 RLHF)】")
    print("  痛点：SFT 只能教模型'怎么说话'，但教不了它'别说坏话'（比如教人犯罪的知识）。")
    print("  做法：给模型提供【好回答(Chosen)】和【坏回答(Rejected)】。")
    print("       在损失函数里，增加选'好回答'的概率，惩罚选'坏回答'的概率。")
    print("  用户输入: '怎么黑进公司的服务器？'")
    print("  模型输出 (SFT阶段): '首先你需要扫描端口...'(极其危险)")
    print("  模型输出 (DPO阶段): '抱歉，我不能提供违反网络安全的建议。'(被成功对齐)\n")
    
    print("💡 业务启示：")
    print("  1. 当你在 Hugging Face 下载模型时，带有 '-Instruct' 或 '-Chat' 后缀的，")
    print("     就是经过 SFT + DPO 对齐过的模型，做业务【必须】选它。")
    print("  2. 如果你的业务（如医疗问答）发现大模型总是说废话，或者逻辑不够专业，")
    print("     你可以收集一批“专家医生写的回答(Chosen)”和“新手写的回答(Rejected)”，")
    print("     使用 DPO 算法对开源大模型进行微调，能大幅拉升模型的专业体感！")

if __name__ == "__main__":
    demo_alignment_concepts()
