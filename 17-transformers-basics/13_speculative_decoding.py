"""
第十三课：大模型超车黑科技 —— 投机解码 (Speculative Decoding)
=============================================================
业务痛点：
  用 72B（720亿）参数的大模型生成文本，每一次前向传播只能蹦出 1 个词。
  无论你给的并发多大，受限于自回归的本质，它就是一个字一个字往外吐。
  这就导致了极高的延迟 (Latency)，用户体验就是回复像挤牙膏。

投机解码的解法：
  引入一个极小的“草稿模型”（Draft Model，比如只有 1.8B 参数，跑得飞快）。
  
  【步骤】：
  1. 草稿模型一口气“猜”出未来 4 个词（极快，几乎不耗时）。
  2. 把这 4 个词一并喂给 72B 的“大模型”（Target Model）。
  3. 大模型利用 GPU 强大的并行矩阵计算能力，一次性**并行验证**这 4 个词对不对。
  4. 如果草稿模型猜对了 3 个，大模型就直接接受这 3 个词，并自己生成第 4 个。
  
  【效果】：
  大模型原本跑 1 次只能出 1 个词，现在跑 1 次出了 4 个词！
  在输出质量**绝对100%无损**的前提下，推理速度飙升 2~3 倍！

本课目标：
  理解大模型推理中的“打草稿”与“审批”机制。
"""

import time

def demo_speculative_decoding():
    print("=" * 60)
    print("🏎️ 演示：投机解码 (Speculative Decoding)")
    print("=" * 60)
    
    print("【传统自回归生成】")
    print("大模型 (72B): (思考0.1秒) -> '苹'")
    print("大模型 (72B): (思考0.1秒) -> '果'")
    print("大模型 (72B): (思考0.1秒) -> '手'")
    print("大模型 (72B): (思考0.1秒) -> '机'")
    print("总耗时：0.4 秒，生成 4 个词。\n")
    
    print("【投机解码机制】")
    print("小模型 (1.8B): (飞速打草稿) -> 猜了4个词：'苹果手机'")
    print("                (因为太小，它只能猜常见套话，耗时极小 0.02秒)")
    print("大模型 (72B): (并行审批这4个词，只跑1次前向传播，耗时0.1秒)")
    print("              审批通过：'苹'✅, '果'✅, '手'✅, '机'✅")
    print("总耗时：0.12 秒，生成 4 个词！速度翻了 3 倍！\n")
    
    print("【当小模型猜错时】")
    print("小模型 (1.8B): 猜了4个词：'苹果好难吃'")
    print("大模型 (72B): 并行审批...")
    print("              审批通过：'苹'✅, '果'✅")
    print("              审批驳回：'好'❌ (大模型觉得这里该接'发'布会)")
    print("大模型立刻纠正：抛弃'好难吃'，大模型自己输出'发'")
    print("最终这 1 步输出了：'苹果发' (3个词)\n")
    
    print("💡 业务启示：")
    print("  1. 投机解码是目前提升大模型出词速度（Token-per-Second）最核心的武器。")
    print("  2. 它需要一个和小模型（Draft）拥有完全相同的词表（Tokenizer）。")
    print("  3. 这种方法保证了最终输出的概率分布和单独跑 72B 完全一致，是【无损加速】。")
    print("  4. 许多开源框架如 vLLM 和 llama.cpp 已经原生支持该功能。")

if __name__ == "__main__":
    demo_speculative_decoding()
